"""
config.py — НАСТРОЙКИ ПРОЕКТА.

Здесь собраны все «числа и секреты» в одном месте, чтобы не искать их по коду:
адрес базы данных, секретный ключ для токенов, время жизни токенов и кодов.
Другие файлы импортируют настройки отсюда: `from config import ...`
"""

